// Small HTML-escaping helper for the print/PDF report. Every value that came
// from the store (accounts, credits, messages, OCM rows, notes, categories,
// statuses, dates) must pass through this before it reaches generated markup.
const ENTITIES = {
  '&': '&amp;',
  '<': '&lt;',
  '>': '&gt;',
  '"': '&quot;',
  "'": '&#39;',
};

export function escapeHtml(value) {
  if (value === null || value === undefined) return '';
  return String(value).replace(/[&<>"']/g, (ch) => ENTITIES[ch]);
}

// Builds the whole printable document from a plain model. The model contains
// raw values; every interpolation below is escaped, including keys that came
// from user data (expense categories, account statuses).
export function buildReportHtml(model) {
  const e = escapeHtml;
  const m = model || {};

  const kpis = (m.kpis || []).map(([value, label]) => (
    `<div class="kpi"><div class="n">${e(value)}</div><div class="l">${e(label)}</div></div>`
  )).join('');

  const tables = (m.tables || []).map((t) => {
    const head = t.header ? `<tr>${t.header.map((h) => `<th>${e(h)}</th>`).join('')}</tr>` : '';
    const rows = (t.rows || []).map((cells) => `<tr>${cells.map((cell, i) => {
      const right = (t.valueRight && i === 1)
        || (t.amountRight && i === 2)
        || (t.lastRight && i === cells.length - 1);
      return `<td${right ? ' style="text-align:right"' : ''}>${e(cell)}</td>`;
    }).join('')}</tr>`).join('');
    const total = t.total === undefined || t.total === null
      ? ''
      : `<tr class="total"><td>Total</td><td style="text-align:right">${e(t.total)}</td></tr>`;
    return `<h2>${e(t.title)}</h2><table>${head}${rows}${total}</table>`;
  }).join('\n  ');

  return `<!DOCTYPE html><html><head><meta charset="utf-8"><title>Territory HQ Report — ${e(m.label)}</title>
<style>
  body{font-family:-apple-system,Segoe UI,Roboto,sans-serif;color:#1a1a1a;padding:32px;max-width:760px;margin:0 auto;}
  h1{font-size:22px;margin:0 0 2px;} .sub{color:#666;margin-bottom:20px;font-size:13px;}
  h2{font-size:14px;text-transform:uppercase;letter-spacing:.5px;color:#888;border-bottom:1px solid #ddd;padding-bottom:4px;margin:24px 0 10px;}
  table{width:100%;border-collapse:collapse;font-size:13px;margin-bottom:8px;}
  td,th{padding:5px 8px;border-bottom:1px solid #eee;text-align:left;}
  .kpis{display:flex;gap:16px;flex-wrap:wrap;margin-bottom:8px;}
  .kpi{flex:1;min-width:110px;border:1px solid #e5e5e5;border-radius:8px;padding:12px;}
  .kpi .n{font-size:24px;font-weight:700;color:#b8860b;} .kpi .l{font-size:11px;color:#777;text-transform:uppercase;}
  .total td{font-weight:700;}
  .foot{margin-top:30px;color:#aaa;font-size:11px;}
</style></head><body>
  <h1>Territory HQ — ${e(m.period)} Report</h1>
  <div class="sub">${e(m.label)} · ${e(m.startStr)} to ${e(m.endStr)} · generated ${e(m.generated)}</div>
  <div class="kpis">
    ${kpis}
  </div>
  ${tables}
  <div class="foot">Generated by Territory HQ</div>
</body></html>`;
}
